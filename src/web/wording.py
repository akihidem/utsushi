"""画面に出す言葉の表（#135）。作る側の内輪の言葉と番号を、学ぶ人が読める言葉にする 1 か所。

判断の芯:
- data/ の字は書き換えない。紙に刷られる字があり（必須 2 種の指紋）、出所の番号は作る側が引くために要る。替えるのは描く時だけ。
- 誰が書いたか・確かめたかの印（J-016）は消さず、言葉だけを替える。床（labels.check）は記録の値のままで見る。
- 替えるのは作る側が書いた字だけ。人が書いた記録・質問・読みと、歌の引用には掛けない。「本人」と書いた人の文まで替えないため。
- この表は内輪の言葉だけ。むずかしい語の言いかえは #317 の表が受け持ち、同じ語を両方に書かない。
- 新しい字は本人の確認の後に入れる（利用者に見せる文の決まり）。今は通り道だけで、表は空なので画面の字は変わらない。
"""

# 「本人」の役の名前。どの名前にするかは本人が決める。
MAKER = "本人"
# 作る側の字（正規表現）と、読む人の字。上から順に替える。
TABLE = ()
# 作る側が残した試行の控え（data/records の note）。人が書く欄なので、表は掛けず、この文だけを文ごと替える。
RECORD_NOTES = {}


def plain(text):
    """作る側が書いた字（data/hypotheses の欄、確かめた人の値）を、読む人の字にする。"""
    for pattern, reader in TABLE:
        text = pattern.sub(reader, text)
    return text


def record_note(text):
    """記録のメモ。人が書いた文はそのまま返す。"""
    return RECORD_NOTES.get(text, text)


def record_no(rid):
    return rid


def sheet_set(name):
    """紙に刷ってある組の版（U-31）。紙の字と照らせるように番号は残す。"""
    return name


def frame(sid):
    """玩具の記録の印から、本の中の場所を言う（NDL-1187053-R0000004-L → コマ 4）。"""
    return f'コマ {sid.split("-R")[1][:7].lstrip("0")}'
