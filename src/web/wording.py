def plain(text):
    """作る側が書いた字（data/hypotheses の欄、確かめた人の値、頁の作りの固定の文）を、読む人の字にする。"""
    for pattern, reader in TABLE:
        text = pattern.sub(reader, text)
    return text


def record_note(text):
    """記録のメモ。人が書いた文はそのまま返す。"""
    return RECORD_NOTES.get(text, text)


def record_no(rid):
    return f"記録の番号 {rid}"


def sheet_set(name):
    """紙に刷ってある組の版（U-31）。紙の字と照らせるように番号は残す。"""
    return f"紙に印刷してある組の番号 {name}"


def frame(sid):
    """玩具の記録の印から、本の中の場所を言う（NDL-1187053-R0000004-L → 本の 4 コマ目）。"""
    return f'本の {sid.split("-R")[1][:7].lstrip("0")} コマ目'
