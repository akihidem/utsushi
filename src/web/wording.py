"""画面に出す言葉の表（#135）。作る側の内輪の言葉と番号を、学ぶ人が読める言葉にする 1 か所。

判断の芯:
- data/ の字は書き換えない。紙に刷られる字があり（必須 2 種の指紋）、出所の番号は作る側が引くために要る。替えるのは描く時だけ。
- 誰が書いたか・確かめたかの印（J-016）は消さず、言葉だけを替える。床（labels.check）は記録の値のままで見る。
- 番号は言い換えを前に付けて出す。番号だけを裸で出さない。
- 替えるのは作る側が書いた字だけ。人が書いた記録・質問・読みと、歌の引用には掛けない。「本人」と書いた人の文まで替えないため。
- この表は内輪の言葉だけ。むずかしい語の言いかえは #317 の表が受け持ち、同じ語を両方に書かない。
- 字は案で、本人の確認待ち（#135）。
"""
import re

# 「本人」の役の名前。序の頁の「作った人」（#329）に合わせ、玩具を作った人と読み違えないように「このサイトを」を足す。
MAKER = "このサイトを作った人"

_FILE = r"data/[a-z0-9./_-]+"
# 作る側の字（正規表現）と、読む人の字。上から順に替えるので、長い形を先に置く。
TABLE = tuple((re.compile(raw), reader) for raw, reader in (
    # 出所の番号と道。読む人が引けない物は、誰の何かの言葉にする
    (r"https://japan-toy-museum\.org/wp-json/wp/v2/monthly/29399", "日本玩具博物館「江戸の手遊び「御来迎」」"),
    (r"（棚卸しの箱 pct:[\d,]+）", ""),
    (rf"棚卸し（{_FILE}）(?:の見立て)?", "作る側の考え"),
    (rf"棚卸しの見立て（{_FILE}）", "作る側の考え"),
    (_FILE, "作る側の一覧"),
    (r"research/\d+", "作る側の計算"),
    (r"雛形 [a-z_]+ の(?:式|床)(?:（[^）]*）)?", "作る側の計算"),
    # 手元の複写は本文を持てず、自分の言葉で短くした物だけを残す（CLAUDE.md の決まり）。それが読む人に分かるように書く
    (r"手元の複写 [AB] 頁 \d+ の解説（要約）", "作る側が読んだ本の解説を、短くまとめた物"),
    (r"手元の複写 [AB] 頁 \d+ が引く(『[^』]+』)（要約。原典は未確認）", r"作る側が読んだ本が引く\1を、短くまとめた物。もとの本はまだ確かめていません"),
    (r"手元の複写 A 頁 \d+ と B 頁 \d+ ?", "作る側が読んだ本"),
    # 作る側の呼び名。data の注は文の区切りが無い物があるので、ここで切る
    (r"家族の pull_string の見立てから", "糸で引くおもちゃの種類から考えた物"),
    (r"棚卸しの(?:見立ての推測|見立て|見込み)", "作る側の考え"),
    # 作る側の「見込み」の言い方。棚卸しの字と同じ文に並ぶので、ここで一緒に替える
    (r"という見込み", "という考え"),
    (r"とある見込み", "とあると考えた"),
    (r"と見込む", "と考える"),
    (r"(?<=[^。])棚卸しの注", "。作る側のメモ"),
    (r"棚卸しの注", "作る側のメモ"),
    (r"棚卸し", "作る側"),
    # 本の場所。「コマ」は国立国会図書館の頁の番号で、開いた時に同じ番号が出る
    (r"NDL コマ (\d+) ?", r"国立国会図書館の本の \1 コマ目"),
    (r"コマ (\d+) ?", r"本の \1 コマ目"),
    (r"([左右])頁", r"\1の頁"),
    # 番号と人。画面のほかの所は「仮説 C」と書く
    (r" ?(?<![A-Za-z0-9])H-([A-Z])(?![A-Za-z0-9])", r"仮説 \1"),
    (r"本人", MAKER),
    (r"Claude Code のセッションが書いた。人の確認はまだ", "AI（Claude）が書いた下書きです。人はまだ確かめていません"),
))

# 作る側が残した試行の控え（data/records の note）。人が書く欄なので、表は掛けず、この文だけを文ごと替える。
RECORD_NOTES = {
    "11-04 の実作の試行（成人 5 人、各 2 案）。記録の全体は docs/process/trials/README.md。見た事の値は本人の答え（動画と写真がどちらの仮説か分からないため、U-32）":
        f"11 月 4 日に、大人 5 人が 2 案ずつ作って試しました。見た事は、{MAKER}が答えました（動画と写真がどちらの仮説か分からないためです）。",
}


def plain(text):
    """作る側が書いた字（data/hypotheses の欄、確かめた人の値）を、読む人の字にする。"""
    for pattern, reader in TABLE:
        text = pattern.sub(reader, text)
    return text


def record_note(text):
    """記録のメモ。人が書いた文はそのまま返す。"""
    return RECORD_NOTES.get(text, text)


def record_no(rid):
    return f"記録の番号 {rid}"


def sheet_set(name):
    """紙に刷ってある組の版（U-31）。紙の字と照らせるように番号は残す。"""
    return f"紙に印刷してある組の番号 {name}"


def frame(sid):
    """玩具の記録の印から、本の中の場所を言う（NDL-1187053-R0000004-L → 本の 4 コマ目）。"""
    return f'本の {sid.split("-R")[1][:7].lstrip("0")} コマ目'
