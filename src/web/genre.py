def middle(sid):
    """玩具の中のジャンル。"""
    return TOY.get(sid) or MIDDLE[hypotheses.load(sid).get("template", "slider_fan")]


def groups(sids):
    """[(大きい側の字, [(中の字, [玩具…]), …]), …]。sids の並びを保ち、0 の中と大きい側は入れない。
    BIG のどこにも入らない中と、2 つの大きい側に入った中がある時は、玩具を黙って落とす・2 度出す代わりに ValueError で止める。"""
    by = {}
    for s in sids:
        by.setdefault(middle(s), []).append(s)
    seen = [m for _, mids in BIG for m in mids]
    twice = sorted({m for m in seen if seen.count(m) > 1})
    if twice:  # 2 つの大きい側に同じ中があると、その玩具が 2 度出る
        raise ValueError(f"2 つの大きい側に入ったジャンル: {'、'.join(twice)}")
    lost = sorted(set(by) - set(seen))
    if lost:
        raise ValueError(f"大きい側に入れ先の無いジャンル: {'、'.join(lost)}")
    out = []
    for big, mids in BIG:
        g = [(m, by[m]) for m in mids if by.get(m)]
        if g:
            out.append((big, g))
    return out
