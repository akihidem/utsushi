TECHO_BANNED = ("の紙", "版 ")
RECORD_NO = re.compile(r"R-\d{4}")


def techo_ok(lines):
    """その字を手帖の作る頁に出してよいか（上の決まりに当たらないか）。"""
    return not any(b in t for t in lines for b in TECHO_BANNED) and not any(RECORD_NO.search(t) for t in lines)


